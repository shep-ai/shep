#!/usr/bin/env python3
"""Generates the Mac app's Swift protocol types from the daemon's OpenRPC schema.

    python3 shep2/tools/swift-codegen/generate.py            # write
    python3 shep2/tools/swift-codegen/generate.py --check    # fail if the files are stale

Arguments (optional): SCHEMA OUT_DIR. Defaults: shep2/schema/openrpc.json and
shep2/macos/Sources/ShepKit/Generated. Python 3.8+, standard library only.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import methods  # noqa: E402
import models  # noqa: E402
from names import SchemaError, case_name, field_name, method_name, type_name  # noqa: E402

# Re-exported so callers and tests reach the naming rules through this module.
__all__ = ["SchemaError", "case_name", "field_name", "method_name", "type_name", "render", "main"]

SHEP2 = os.path.normpath(os.path.join(HERE, "..", ".."))
DEFAULT_SCHEMA = os.path.join(SHEP2, "schema", "openrpc.json")
DEFAULT_OUT = os.path.join(SHEP2, "macos", "Sources", "ShepKit", "Generated")
CHECK_FLAG = "--check"
HEADER = [
    "// Generated by shep2/tools/swift-codegen/generate.py from shep2/schema/openrpc.json.",
    "// Do not edit. Change the Rust types, refresh the schema",
    "// (SHEP_UPDATE_SCHEMA=1 cargo test -p shep-rpc --test schema), then run the generator.",
    "",
    "import Foundation",
    "",
]


def render(document):
    """`{file name: contents}` for every generated file."""
    model_lines = []
    for name, schema in sorted(document["components"]["schemas"].items()):
        model_lines += models.render_component(name, schema) + [""]
    return {
        "Models.swift": "\n".join(HEADER + model_lines).rstrip() + "\n",
        "Methods.swift": "\n".join(HEADER + methods.render(document)).rstrip() + "\n",
    }


def read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def main(argv):
    check = CHECK_FLAG in argv
    paths = [a for a in argv if a != CHECK_FLAG]
    schema_path = paths[0] if paths else DEFAULT_SCHEMA
    out_dir = paths[1] if len(paths) > 1 else DEFAULT_OUT
    with open(schema_path, encoding="utf-8") as f:
        files = render(json.load(f))
    stale = [name for name, text in files.items() if read(os.path.join(out_dir, name)) != text]
    if check:
        for name in stale:
            print(f"{os.path.join(out_dir, name)} is out of date; run python3 shep2/tools/swift-codegen/generate.py", file=sys.stderr)
        return 1 if stale else 0
    os.makedirs(out_dir, exist_ok=True)
    for name in stale:
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as f:
            f.write(files[name])
        print(f"wrote {os.path.join(out_dir, name)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
